import test from 'node:test';
import assert from 'node:assert/strict';
import {existsSync} from 'node:fs';
import {readFile} from 'node:fs/promises';
test('contact design preview preserves the inquiry contract without factory illustration',async()=>{
 const file=new URL('../../dist/design-preview/contact/index.html',import.meta.url);
 assert.ok(existsSync(file),'contact design preview is missing');
 const html=await readFile(file,'utf8');
 assert.ok(html.includes('quote-redesign'));
 assert.equal((html.match(/<h1\b/g)||[]).length,1);
 const section=html.match(/<section\b[^>]*quote-redesign[\s\S]*?<script src=/)[0];
 assert.ok(!section.includes('<img'));
 const contacts=html.match(/<div class="direct-options">([\s\S]*?)<div class="next-steps">/)[1];
 assert.equal((contacts.match(/<a\b/g)||[]).length,1);
 assert.ok(contacts.includes('href="https://wa.me/6581603123"'));
 assert.ok(!contacts.includes('mailto:'));
 assert.ok(!contacts.includes('tel:'));
 assert.ok(contacts.includes('zhous6850@gmail.com'));
 assert.ok(contacts.includes('+86 574 8696 1222'));
 const form=html.match(/<form\b[^>]*corncomp-inquiry-form[\s\S]*?<\/form>/)[0];
 assert.ok(form.includes('action="/api/inquiry" method="post"'));
 assert.deepEqual([...form.matchAll(/<(?:input|textarea)\b[^>]*name="([^"]+)"/g)].map(m=>m[1]),['name','email','company','country','phone','quantity','productName','productSku','category','message','sourcePath','website']);
 assert.equal((form.match(/class="required-mark"/g)||[]).length,5);
 assert.ok(form.includes('data-sitekey="0x4AAAAAAFR8Uz-WseWno-sx"'));
 assert.ok(form.includes('id="contact-details"'));
 assert.ok(form.includes('id="packaging-details"'));
 const formal=await readFile(new URL('../../dist/contact/index.html',import.meta.url),'utf8');
 assert.ok(formal.includes('quote-redesign'));
});
